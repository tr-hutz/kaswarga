export function applyKonfirmasiFilters(
    query,
    {
        tahun,
        rtId,
        wargaId,
        status
    }
) {

    /*
     |--------------------------------------------------------------------------
     | FILTER TAHUN
     |--------------------------------------------------------------------------
     */

    if (tahun) {

        query =
            query.eq(
                'tahun',
                tahun
            )
    }

    /*
     |--------------------------------------------------------------------------
     | FILTER RT
     |--------------------------------------------------------------------------
     */

    if (rtId) {

        query =
            query.eq(
                'rt_id',
                rtId
            )
    }

    /*
     |--------------------------------------------------------------------------
     | FILTER WARGA
     |--------------------------------------------------------------------------
     */

    if (wargaId) {

        query =
            query.eq(
                'warga_id',
                wargaId
            )
    }

    /*
     |--------------------------------------------------------------------------
     | FILTER STATUS
     |--------------------------------------------------------------------------
     */

    if (status) {

        query =
            query.eq(
                'status',
                status
            )
    }

    return query
}